// In-memory Web Storage for tests that run in the `node` environment (no `localStorage` there),
// and for DOM tests that need a storage they fully control.
export function createLocalStorageMock() {
  const store = new Map()
  return {
    getItem(key) {
      return store.has(key) ? store.get(key) : null
    },
    setItem(key, value) {
      store.set(key, String(value))
    },
    removeItem(key) {
      store.delete(key)
    },
    clear() {
      store.clear()
    },
  }
}
